#!/usr/bin/env bash
# 12-bashrc — Expose user toolchains to interactive and SSH-launched shells.
#
# User tier: runs as the deploy user (non-root).
# The root-tier 40-profile step writes PATH into ~/.profile, but that is only
# sourced by login shells. VS Code integrated terminals, `bash` without `-l`,
# and most tool-launched shells are non-login — they never see ~/.profile.
# SSH-launched non-interactive Bash shells can also read ~/.bashrc, but Debian's
# default ~/.bashrc returns immediately for non-interactive shells. Put the
# managed block before that guard so editor servers inherit the toolchain PATH.
#
# Idempotent: the block is bounded by stable BEGIN/END markers so re-running
# is a no-op and an updated snippet replaces only the marker block.
#
# Run as the deploy user (./user/init.sh 12-bashrc).

set -euo pipefail

# shellcheck source=../lib/common.sh
. "$(dirname "${BASH_SOURCE[0]}")/../lib/common.sh"

BASHRC="$HOME/.bashrc"
MARKER_BEGIN='# --- BEGIN bootstrap-managed PATH block (do not edit between these lines) ---'
MARKER_END='# --- END bootstrap-managed PATH block ---'

# Keep this block lightweight: SSH startup must not run nvm, direnv, or any
# other interactive setup. The default nvm alias is an exact version written
# by 35-node; other aliases are left to interactive nvm initialization.
# shellcheck disable=SC2016
SNIPPET_CONTENT='# Make installed tools available before the non-interactive .bashrc guard.
for _bp_dir in "$HOME/.local/bin" "$HOME/.kilo/bin" "$HOME/.local/go/bin" "$HOME/go/bin"; do
    if [ -d "$_bp_dir" ]; then
        case ":$PATH:" in
            *":$_bp_dir:"*) ;;
            *) PATH="$_bp_dir:$PATH" ;;
        esac
    fi
done
if [ -r "$HOME/.nvm/alias/default" ]; then
    IFS= read -r _bp_node_version < "$HOME/.nvm/alias/default" || :
    if [[ $_bp_node_version =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
        _bp_dir="$HOME/.nvm/versions/node/v$_bp_node_version/bin"
        if [ -d "$_bp_dir" ]; then
            case ":$PATH:" in
                *":$_bp_dir:"*) ;;
                *) PATH="$_bp_dir:$PATH" ;;
            esac
        fi
    fi
fi
unset _bp_dir
unset _bp_node_version
export PATH'

if [[ ! -f "$BASHRC" ]]; then
  echo "==> ${BASHRC} does not exist; creating with the bootstrap PATH block."
  {
    echo "$MARKER_BEGIN"
    printf '%s\n' "$SNIPPET_CONTENT"
    echo "$MARKER_END"
    echo "# $(id -un)'s bashrc (generated by 12-bashrc)"
  } > "$BASHRC"
  chmod 0644 "$BASHRC"
  echo "==> Wrote ${BASHRC}."
  exit 0
fi

# Detect existing marker pair.
has_begin=0
has_end=0
grep -Fq "$MARKER_BEGIN" "$BASHRC" && has_begin=1
grep -Fq "$MARKER_END"   "$BASHRC" && has_end=1

if (( has_begin )) && (( has_end )); then
  existing_block="$(awk -v b="$MARKER_BEGIN" -v e="$MARKER_END" '
    $0 == b { capture = 1; next }
    $0 == e { capture = 0; next }
    capture  { print }
  ' "$BASHRC")"
  if [[ "$existing_block" == "$SNIPPET_CONTENT" && "$(sed -n '1p' "$BASHRC")" == "$MARKER_BEGIN" ]]; then
    echo "==> ${BASHRC} — bootstrap PATH block already up to date; skipping."
    exit 0
  fi
  mode="move"
elif (( has_begin )) || (( has_end )); then
  echo "ERROR: ${BASHRC} contains only one of the bootstrap markers — refusing to edit." >&2
  exit 1
else
  mode="prepend"
fi

BASHRC_NEW="$(mktemp "${HOME}/.bashrc.bootstrap.XXXXXX")"
# shellcheck disable=SC2064
trap 'rm -f "$BASHRC_NEW"' EXIT

{
  printf '%s\n%s\n%s\n' "$MARKER_BEGIN" "$SNIPPET_CONTENT" "$MARKER_END"
  awk -v begin="$MARKER_BEGIN" -v end="$MARKER_END" '
    $0 == begin { in_block = 1; next }
    $0 == end && in_block { in_block = 0; next }
    !in_block { print }
  ' "$BASHRC"
} > "$BASHRC_NEW"

mv "$BASHRC_NEW" "$BASHRC"
trap - EXIT
# mktemp creates 0600; the create path above uses 0644 — normalize so
# the two paths leave the same mode.
chmod 0644 "$BASHRC"

if [[ "$mode" == "move" ]]; then
  echo "==> ${BASHRC} — bootstrap PATH block moved before the non-interactive guard."
else
  echo "==> ${BASHRC} — bootstrap PATH block prepended."
fi
